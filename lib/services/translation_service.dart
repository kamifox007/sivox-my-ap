class TranslationService {
  static final ValueNotifier<Language> currentLanguage = ValueNotifier(
    Language.en,
  );

  static void setLanguage(Language lang) {
    currentLanguage.value = lang;
  }

  static void initSystemLanguage() {
    try {
      final locale = PlatformDispatcher.instance.locale.languageCode;
      for (var lang in Language.values) {
        if (lang.name == locale) {
          currentLanguage.value = lang;
          return;
        }
      }
    } catch (e) {
      debugPrint('Error initializing system language: $e');
    }
  }

  static bool get isRtl => currentLanguage.value == Language.ar;

  static String translate(String key) {
    final translated = _translations[currentLanguage.value]?[key];
    if (translated != null) return translated;

    // Fallback to English
    final fallback = _translations[Language.en]?[key];
    return fallback ?? key;
  }

  static String translateWithArgs(String key, List<dynamic> args) {
    String text = translate(key);
    for (int i = 0; i < args.length; i++) {
      text = text.replaceAll('{$i}', args[i].toString());
    }
    return text;
  }

